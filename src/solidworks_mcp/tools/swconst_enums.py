"""Search the SolidWorks ``swconst`` enums: names and values, offline.

The index (``data/swconst_enums.json``) is generated by
``src/utils/generate_swconst_enums.py`` from ``SolidWorks.Interop.swconst.dll``
by reflection and committed, so the lookup works without SolidWorks. It
records which SolidWorks release it came from. SolidWorks keeps an enum
member's value across releases and only adds members, so values hold for
older releases too; a member newer than the user's release won't exist
there.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

from pydantic import BaseModel, Field

#: The committed index.
ENUM_INDEX_FILE = Path(__file__).resolve().parents[1] / "data" / "swconst_enums.json"

#: Enums whose members are listed in full; later matches give only a count.
_ENUMS_WITH_MEMBERS = 3
#: Members listed per enum at most.
_MEMBERS_PER_ENUM = 250

_INTEGER = re.compile(r"^[+-]?(0x[0-9a-f]+|\d+)$", re.IGNORECASE)
_NAMESPACE = re.compile(r"^(solidworks\.interop\.)?swconst\.", re.IGNORECASE)


class EnumMember(BaseModel):
    """One enum member.

    Attributes:
        enum (str): The enum it belongs to.
        member (str): Its name.
        value (int): Its value.
    """

    enum: str = Field(description="The enum, e.g. swBodyOperationType_e")
    member: str = Field(description="The member, e.g. SWBODYCUT")
    value: int = Field(description="Its integer value")


class EnumMatch(BaseModel):
    """An enum whose name matched.

    Attributes:
        enum (str): Its name.
        member_count (int): How many members it has.
        members (dict[str, int] | None): Member -> value, in declaration
            order; None past the first few matches.
        members_truncated (bool): True when not every member is listed.
    """

    enum: str = Field(description="The enum's name")
    member_count: int = Field(description="Number of members")
    members: dict[str, int] | None = Field(
        default=None,
        description="Member -> value in declaration order; null past the first matches",
    )
    members_truncated: bool = Field(
        default=False, description="True when not every member is listed"
    )


class EnumSearch(BaseModel):
    """What a search found.

    Attributes:
        enums (list[EnumMatch]): Enums whose name matched, best first.
        members (list[EnumMember]): Members whose name (or value) matched.
        note (str | None): How to narrow the search, when it was cut short.
    """

    enums: list[EnumMatch] = Field(default_factory=list)
    members: list[EnumMember] = Field(default_factory=list)
    note: str | None = None


@lru_cache(maxsize=4)
def _read(path: str, stamp: tuple[int, int]) -> dict[str, Any]:
    """Parse an index file; cached while the file is unchanged.

    Args:
        path (str): The file.
        stamp (tuple[int, int]): Its mtime and size, so an edit re-reads it.

    Returns:
        dict[str, Any]: The parsed index.
    """
    with open(path, encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, dict) or not isinstance(data.get("enums"), dict):
        raise ValueError(f"{path} is not a swconst enum index")
    return data


def load_enum_index(path: Path | None = None) -> dict[str, Any]:
    """Read the enum index.

    Args:
        path (Path | None): The index file; the committed one by default.

    Returns:
        dict[str, Any]: ``source`` (where it came from) and ``enums``
        (enum -> member -> value).

    Raises:
        OSError: The file can't be read.
        ValueError: It isn't an enum index.
    """
    target = path or ENUM_INDEX_FILE
    stat = target.stat()
    return _read(str(target), (stat.st_mtime_ns, stat.st_size))


def _score(name: str, query: str, exact: int, prefix: int, inside: int) -> int:
    """Score a name against a lowercased query: 0 when it doesn't match."""
    lowered = name.lower()
    if lowered == query:
        return exact
    if lowered.startswith(query):
        return prefix
    if query in lowered:
        return inside
    return 0


def _all_words(name: str, words: list[str]) -> bool:
    lowered = name.lower()
    return all(word in lowered for word in words)


def _enum_match(name: str, members: dict[str, int], full: bool) -> EnumMatch:
    if not full:
        return EnumMatch(enum=name, member_count=len(members))
    listed = dict(list(members.items())[:_MEMBERS_PER_ENUM])
    return EnumMatch(
        enum=name,
        member_count=len(members),
        members=listed,
        members_truncated=len(listed) < len(members),
    )


def _by_value(enums: dict[str, dict[str, int]], value: int, limit: int) -> EnumSearch:
    found = [
        EnumMember(enum=enum, member=member, value=number)
        for enum, members in enums.items()
        for member, number in members.items()
        if number == value
    ]
    note = None
    if len(found) > limit:
        note = (
            f"{len(found)} members have the value {value}; showing {limit}. "
            "Search the enum's name for its members instead."
        )
    return EnumSearch(members=found[:limit], note=note)


def search_enums(
    index: dict[str, Any], query: str, max_results: int = 20
) -> EnumSearch:
    """Find enums and members by name, part of a name, or value.

    Matching ignores case. ``Enum.Member`` (``swBodyOperationType_e.SWBODYCUT``)
    finds that member; a number (``15902``, ``0x3E1E``) finds the members
    with that value; several words must all appear in a name. Exact names
    rank first, then names that start with the query, then names that
    contain it.

    Args:
        index (dict[str, Any]): The enum index.
        query (str): What to find.
        max_results (int): How many enums, and how many members, to return.

    Returns:
        EnumSearch: The matches.
    """
    enums: dict[str, dict[str, int]] = index.get("enums", {})
    text = _NAMESPACE.sub("", query.strip())
    if _INTEGER.match(text):
        return _by_value(enums, int(text, 0), max_results)

    enum_part, dot, member_part = text.partition(".")
    if dot and enum_part and member_part:
        wanted = enum_part.lower()
        for name, members in enums.items():
            if name.lower() in (wanted, f"{wanted}_e"):
                hits = [
                    EnumMember(enum=name, member=m, value=v)
                    for m, v in members.items()
                    if m.lower() == member_part.lower()
                ]
                if hits:
                    return EnumSearch(members=hits)
        text = member_part

    lowered = text.lower()
    words = lowered.split()
    single = len(words) == 1
    scored_enums: list[tuple[int, str]] = []
    scored_members: list[tuple[int, str, str, int]] = []
    for name, members in enums.items():
        if single:
            score = max(
                _score(name, lowered, 100, 60, 30),
                100 if name.lower() == f"{lowered}_e" else 0,
            )
        else:
            score = 20 if _all_words(name, words) else 0
        if score:
            scored_enums.append((score, name))
        for member, value in members.items():
            if single:
                member_score = _score(member, lowered, 90, 50, 25)
            else:
                member_score = 20 if _all_words(member, words) else 0
            if member_score:
                scored_members.append((member_score, name, member, value))

    scored_enums.sort(key=lambda item: (-item[0], item[1].lower()))
    # A member of an enum listed in full is already in the reply.
    listed = {
        name
        for _, name in scored_enums[: min(_ENUMS_WITH_MEMBERS, max_results)]
        if len(enums[name]) <= _MEMBERS_PER_ENUM
    }
    scored_members = [hit for hit in scored_members if hit[1] not in listed]
    scored_members.sort(key=lambda item: (-item[0], item[1].lower(), item[2].lower()))
    result = EnumSearch(
        enums=[
            _enum_match(name, enums[name], position < _ENUMS_WITH_MEMBERS)
            for position, (_, name) in enumerate(scored_enums[:max_results])
        ],
        members=[
            EnumMember(enum=enum, member=member, value=value)
            for _, enum, member, value in scored_members[:max_results]
        ],
    )
    cut = [
        f"{len(found)} {kind}"
        for found, kind in ((scored_enums, "enums"), (scored_members, "members"))
        if len(found) > max_results
    ]
    if cut:
        result.note = (
            f"Matched {' and '.join(cut)}; showing {max_results} of each. "
            "Use a longer part of the name, or the exact enum name."
        )
    return result
